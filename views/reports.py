from __future__ import annotations

import pandas as pd
import plotly.graph_objects as go
import streamlit as st

from core import theme as T
from core.data import Ctx, LoadReport
from core.expenses import book, daily_allocation


def _pl(ctx: Ctx) -> pd.DataFrame:
    exp = daily_allocation(book(), ctx.start, ctx.end)
    tot = exp.sum(axis=1) if not exp.empty and exp.shape[1] else pd.Series(0.0, index=ctx.daily.index)
    pl = pd.DataFrame({
        "Net Sales": ctx.daily["Net Sales"],
        "Refunds": ctx.daily["Refunds"],
        "Tips": ctx.daily["Tips"],
        "Processing Fees": ctx.daily["Processing Fees"],
        "Operating Expenses": tot.reindex(ctx.daily.index, fill_value=0),
    })
    pl["Profit"] = pl["Net Sales"] - pl["Processing Fees"] - pl["Operating Expenses"]
    return pl


def _month_report_html(ctx: Ctx, month: pd.Period, pl_m: pd.DataFrame) -> str:
    s, e = month.start_time, month.end_time.normalize()
    prev = (month - 1)
    row = pl_m.loc[month.start_time] if month.start_time in pl_m.index else None
    tx = ctx.tx_all[(ctx.tx_all["Day"] >= s) & (ctx.tx_all["Day"] <= e)]
    ptx = ctx.tx_all[(ctx.tx_all["Day"] >= prev.start_time) & (ctx.tx_all["Day"] <= prev.end_time.normalize())]
    pay, ppay = tx[tx["Event Type"] == "Payment"], ptx[ptx["Event Type"] == "Payment"]
    net, pnet = tx["Net Sales"].sum(), ptx["Net Sales"].sum()
    it = ctx.items_all[(ctx.items_all["Day"] >= s) & (ctx.items_all["Day"] <= e)] if ctx.has_items else pd.DataFrame()
    top = it.groupby("Item").agg(Units=("Qty", "sum"), Net=("Net Sales", "sum")).nlargest(10, "Net") \
        if not it.empty else pd.DataFrame()

    def kpi(lbl, v, d=None):
        dd = f'<div style="font-size:12px;color:{T.GOOD if (d or 0) >= 0 else T.BAD}">{d:+.1f}% vs {prev.strftime("%b")}</div>' \
            if d is not None else ""
        return (f'<div style="flex:1;background:#fff;border-radius:16px;padding:14px 18px">'
                f'<div style="font-size:12px;color:{T.MUTED}">{lbl}</div>'
                f'<div style="font-size:24px;font-weight:600">{v}</div>{dd}</div>')

    kpis = "".join([
        kpi("Net sales", T.money(net), T.pct(net, pnet)),
        kpi("Transactions", f"{len(pay):,}", T.pct(len(pay), len(ppay))),
        kpi("Average ticket", T.money(pay["Net Sales"].mean() if len(pay) else 0, 2)),
        kpi("Est. profit", T.money(row["Profit"]) if row is not None else "–"),
    ])
    rows = "".join(f"<tr><td>{T.esc(i)}</td><td style='text-align:right'>{r['Units']:,.0f}</td>"
                   f"<td style='text-align:right'>{T.money(r['Net'])}</td></tr>" for i, r in top.iterrows())
    return f"""<!doctype html><html><head><meta charset="utf-8"><title>{month.strftime("%B %Y")} sales report</title>
<style>body{{font-family:Poppins,system-ui,sans-serif;background:{T.CANVAS};color:{T.INK};padding:32px;max-width:900px;margin:auto}}
h1{{font-weight:600}} table{{width:100%;border-collapse:collapse;background:#fff;border-radius:16px;overflow:hidden}}
td,th{{padding:8px 14px;border-bottom:1px solid #EEF0FA;font-size:14px;text-align:left}} th{{color:{T.MUTED};font-weight:500}}
@media print{{body{{background:#fff}}}}</style></head><body>
<h1>{month.strftime("%B %Y")} sales report</h1><p style="color:{T.MUTED}">Generated by Databased from Square exports.
Voided transactions excluded; refunds netted against sales. Profit uses the expense book (estimates included).</p>
<div style="display:flex;gap:12px;margin:18px 0">{kpis}</div>
<h3>Top items</h3><table><tr><th>Item</th><th style="text-align:right">Units</th><th style="text-align:right">Net sales</th></tr>{rows}</table>
</body></html>"""


def _quality(rep: LoadReport | None, label: str) -> None:
    if rep is None:
        st.caption(f"No {label} loaded.")
        return
    rows = [("Files", rep.files), ("Rows read", rep.rows_read), ("Rows kept", rep.rows_kept),
            ("Unreadable files", len(rep.unreadable)), ("Rows with bad dates (rejected)", rep.bad_dates),
            ("Duplicate rows dropped", rep.duplicates), ("Voided (excluded)", rep.voided), *rep.extra.items()]
    st.dataframe(pd.DataFrame(rows, columns=[label.capitalize(), "Count"]), hide_index=True, width="stretch")
    if rep.unreadable:
        st.warning("Couldn't read: " + ", ".join(rep.unreadable))


def render(ctx: Ctx) -> None:
    T.page_header("Reports", ctx.range_label())
    if not ctx.has_tx:
        st.info("Upload transaction exports to build reports.")
        return
    pl = _pl(ctx)
    m = pl.resample("MS").sum()
    m["Margin %"] = (m["Profit"] / m["Net Sales"].where(m["Net Sales"] != 0) * 100).astype(float)
    rev, fees, exp, prof = pl["Net Sales"].sum(), pl["Processing Fees"].sum(), pl["Operating Expenses"].sum(), pl["Profit"].sum()
    T.tiles([
        T.tile("Net sales", T.money(rev)),
        T.tile("Processing fees", T.money(fees), f"{fees / rev * 100:.1f}% of sales" if rev else None),
        T.tile("Operating expenses", T.money(exp), "add them on the Expenses page" if exp == 0 else None,
               None if exp else False),
        T.tile("Estimated profit", T.money(prof), f"{prof / rev * 100:.1f}% margin" if rev else None, prof >= 0),
    ])
    st.markdown("")

    with st.container(key="card_plchart"):
        T.card_header("Monthly profit & loss", "Net sales, costs and estimated profit")
        fig = go.Figure()
        xl = m.index.strftime("%b %Y")
        fig.add_bar(x=xl, y=m["Net Sales"], name="Net sales", marker=dict(color=T.INDIGO, cornerradius=4))
        fig.add_bar(x=xl, y=m["Operating Expenses"] + m["Processing Fees"], name="Expenses + fees",
                    marker=dict(color=T.PEACH, cornerradius=4))
        fig.add_scatter(x=xl, y=m["Profit"], name="Profit", mode="lines+markers",
                        line=dict(color=T.ORANGE, width=2.4),
                        marker=dict(size=7, color="#fff", line=dict(color=T.ORANGE, width=2)))
        fig.update_layout(barmode="group", bargap=0.3, bargroupgap=0.1)
        fig.update_yaxes(tickprefix="$")
        fig.add_hline(y=0, line=dict(color="#D9DBEE", width=1))
        T.chart(fig, 320, key="rp_pl")

    a, b = st.columns([1.6, 1], gap="medium")
    with a, st.container(key="card_pltable"):
        T.card_header("Monthly P&L table")
        show = m.copy()
        show.index = show.index.strftime("%Y-%m")
        st.dataframe(show, width="stretch", column_config={
            c: st.column_config.NumberColumn(format="dollar") for c in show.columns if c != "Margin %"
        } | {"Margin %": st.column_config.NumberColumn(format="%.1f%%")})
    with b, st.container(key="card_downloads"):
        T.card_header("Downloads", "Exports for your accountant or your records")
        st.download_button("Monthly P&L (CSV)", show.to_csv().encode(), "monthly_pl.csv", "text/csv",
                           width="stretch")
        d = ctx.daily.copy()
        d[f"Rolling Net Sales ({ctx.window}d)"] = d["Net Sales"].rolling(ctx.window, min_periods=1).mean()
        st.download_button("Daily summary (CSV)", d.to_csv().encode(), "daily_summary.csv", "text/csv",
                           width="stretch")
        months = pd.period_range(pd.Timestamp(ctx.start), pd.Timestamp(ctx.end), freq="M")[::-1]
        mo = st.selectbox("Monthly report", months, format_func=lambda p: p.strftime("%B %Y"), key="rp_month")
        full_m = _pl_full_months(ctx)
        st.download_button(f"{mo.strftime('%B %Y')} report (printable HTML)", _month_report_html(ctx, mo, full_m).encode(),
                           f"report-{mo}.html", "text/html", width="stretch")

    with st.container(key="card_quality"):
        T.card_header("Data quality", "Rejected rows are surfaced here, not silently dropped")
        q1, q2 = st.columns(2)
        with q1:
            _quality(ctx.tx_report, "transactions")
        with q2:
            _quality(ctx.items_report, "items")


def _pl_full_months(ctx: Ctx) -> pd.DataFrame:
    d = ctx.daily_all
    exp = daily_allocation(book(), d.index.min().date(), d.index.max().date())
    tot = exp.sum(axis=1) if not exp.empty and exp.shape[1] else pd.Series(0.0, index=d.index)
    p = pd.DataFrame({"Net Sales": d["Net Sales"], "Fees": d["Processing Fees"], "Exp": tot})
    p["Profit"] = p["Net Sales"] - p["Fees"] - p["Exp"]
    return p.resample("MS").sum()
